// Opens the local SQLite database safely and applies versioned migrations.
//
// Guarantees:
//   - never silently recreates a personal database that existed before (config.db_created_at)
//   - never applies a migration whose contents differ from migrations/LOCK.json
//   - refuses databases that have migrations this code does not know (downgrade protection)
//   - runs `beforeMigrate` (an encrypted, verified backup) before touching an existing database
//   - records applied migrations in `d1_migrations` (name kept from the D1 origins)
import { createHash } from "node:crypto";
import { chmodSync, existsSync, readdirSync, readFileSync } from "node:fs";
import { join } from "node:path";
import { writeSettings, type LocalConfig } from "./config";
import { LocalD1 } from "./d1-sqlite";

export const MIGRATIONS_TABLE = "d1_migrations";

export interface MigrationFile {
  name: string;
  sql: string;
  sha256: string;
}

export function readMigrations(appRoot: string): MigrationFile[] {
  const dir = join(appRoot, "migrations");
  const lockFile = join(dir, "LOCK.json");
  const lock: Record<string, string> = existsSync(lockFile) ? JSON.parse(readFileSync(lockFile, "utf8")) : {};
  return readdirSync(dir)
    .filter((f) => f.endsWith(".sql"))
    .sort()
    .map((name) => {
      const sql = readFileSync(join(dir, name), "utf8");
      const sha256 = createHash("sha256").update(sql).digest("hex");
      if (lock[name] && lock[name] !== sha256) throw new Error(`Migration ${name} differs from migrations/LOCK.json. Refusing to run modified migration history.`);
      return { name, sql, sha256 };
    });
}

export function appliedMigrations(d1: LocalD1): string[] {
  d1.db.exec(`CREATE TABLE IF NOT EXISTS ${MIGRATIONS_TABLE} (id INTEGER PRIMARY KEY AUTOINCREMENT, name TEXT UNIQUE, applied_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL)`);
  return (d1.db.prepare(`SELECT name FROM ${MIGRATIONS_TABLE} ORDER BY id`).all() as { name: string }[]).map((r) => r.name);
}

export function pendingMigrations(d1: LocalD1, all: MigrationFile[]) {
  const applied = appliedMigrations(d1);
  const known = new Set(all.map((m) => m.name));
  const unknown = applied.filter((n) => !known.has(n));
  if (unknown.length) {
    throw new Error(`This database was upgraded by a newer Career Atlas (unknown migrations: ${unknown.join(", ")}). Update the app instead of downgrading.`);
  }
  return all.filter((m) => !applied.includes(m.name));
}

/** Applies migrations, each in its own transaction (statement breakpoints as generated by drizzle-kit). */
export function applyMigrations(d1: LocalD1, migrations: MigrationFile[]) {
  appliedMigrations(d1); // ensures the bookkeeping table exists
  for (const m of migrations) {
    d1.transaction(() => {
      for (const stmt of m.sql.split("--> statement-breakpoint")) if (stmt.trim()) d1.db.exec(stmt);
      d1.db.prepare(`INSERT INTO ${MIGRATIONS_TABLE} (name) VALUES (?)`).run(m.name);
    });
  }
  const fk = d1.db.prepare("PRAGMA foreign_key_check").all();
  if (fk.length) throw new Error(`Foreign-key check failed after migration (${fk.length} problems)`);
}

export function userTables(d1: LocalD1): string[] {
  return (
    d1.db
      .prepare(`SELECT name FROM sqlite_master WHERE type = 'table' AND name NOT LIKE 'sqlite_%' AND name NOT LIKE '_cf_%' AND name <> '${MIGRATIONS_TABLE}' ORDER BY name`)
      .all() as { name: string }[]
  ).map((r) => r.name);
}

export function tableCounts(d1: LocalD1): Record<string, number> {
  const out: Record<string, number> = {};
  for (const t of userTables(d1)) out[t] = Number((d1.db.prepare(`SELECT COUNT(*) AS n FROM "${t}"`).get() as { n: number }).n);
  return out;
}

export function schemaVersion(d1: LocalD1): string | null {
  return appliedMigrations(d1).at(-1) ?? null;
}

export interface OpenOptions {
  /** Called with the open database before pending migrations run on a database that already has data. */
  beforeMigrate?: (d1: LocalD1, pending: MigrationFile[]) => Promise<void>;
  /** Allow creating the database if it does not exist (default true for a brand-new install). */
  allowCreate?: boolean;
}

export async function openDatabase(cfg: LocalConfig, opts: OpenOptions = {}): Promise<{ d1: LocalD1; created: boolean; migrated: string[] }> {
  const exists = existsSync(cfg.dbPath);
  if (!exists && cfg.settings.db_created_at) {
    throw new Error(
      `The Career Atlas database is missing: ${cfg.dbPath}\n` +
        `It was created on ${cfg.settings.db_created_at}. Refusing to create an empty replacement.\n` +
        `Restore it from ~/CareerAtlasBackups (npm run local -- restore --help), or move it back.`,
    );
  }
  if (!exists && opts.allowCreate === false) throw new Error(`Database not found: ${cfg.dbPath}`);

  const d1 = new LocalD1(cfg.dbPath);
  // Owner-only access to the database files (SQLite gives -wal/-shm the main file's mode).
  for (const f of [cfg.dbPath, `${cfg.dbPath}-wal`, `${cfg.dbPath}-shm`]) if (existsSync(f)) chmodSync(f, 0o600);
  try {
    const integrity = d1.db.prepare("PRAGMA quick_check").get() as { quick_check: string };
    if (integrity.quick_check !== "ok") throw new Error(`Database integrity check failed: ${integrity.quick_check}. Restore from a backup.`);

    const all = readMigrations(cfg.appRoot);
    const pending = pendingMigrations(d1, all);
    const hasData = userTables(d1).length > 0;
    if (pending.length && hasData && opts.beforeMigrate) await opts.beforeMigrate(d1, pending);
    if (pending.length) applyMigrations(d1, pending);

    if (!exists) writeSettings(cfg, { db_created_at: new Date().toISOString() });
    return { d1, created: !exists, migrated: pending.map((m) => m.name) };
  } catch (e) {
    d1.close();
    throw e;
  }
}
